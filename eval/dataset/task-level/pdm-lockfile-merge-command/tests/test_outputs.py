def test_invalid_inputs_are_rejected(tmp_path):
    # precondition: the merge command itself is available
    assert run_merge(tmp_path, "merge-lock", "--help").returncode == 0
    base = write(tmp_path / "base.lock", BASE_LOCK)
    ours = write(tmp_path / "ours.lock", OURS_LOCK)
    # missing file
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(tmp_path / "absent.lock"))
    assert result.returncode != 0
    # pylock.toml is not a PDM lockfile
    pylock = write(tmp_path / "pylock.toml", PYLOCK_DOC)
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(pylock))
    assert result.returncode != 0
    # malformed TOML
    bad = write(tmp_path / "bad.lock", "this is [not toml")
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(bad))
    assert result.returncode != 0


def test_merged_lockfile_is_consumable_by_pdm(tmp_path, three_locks):
    """The merged document must load through PDM's own lockfile machinery."""
    base, ours, theirs = three_locks
    out = tmp_path / "merged.lock"
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out))
    assert result.returncode == 0, result.stderr
    check = subprocess.run(
        [
            sys.executable,
            "-c",
            (
                "import sys, tomllib\n"
                "from pdm.project.lockfile.pdmlock import PDMLock\n"
                "from pdm.utils import parse_version\n"
                "data = tomllib.load(open(sys.argv[1], 'rb'))\n"
                "spec = PDMLock.spec_version\n"
                "version = parse_version(data['metadata']['lock_version'])\n"
                "assert version.major == spec.major and version.minor <= spec.minor, version\n"
                "names = [p['name'] for p in data['package']]\n"
                "assert names == sorted(names)\n"
                "assert all('version' in p for p in data['package'])\n"
                "print('ok')\n"
            ),
            str(out),
        ],
        env=PDM_ENV,
        capture_output=True,
        text=True,
        timeout=60,
    )
    assert check.returncode == 0, check.stderr
    assert "ok" in check.stdout
