PYLOCK_DOC = 'lock-version = "1.0"\ncreated-by = "pdm"\n'


def run_merge(cwd: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "pdm", *args],
        cwd=cwd,
        env=PDM_ENV,
        capture_output=True,
        text=True,
        timeout=120,
    )


def write(path: Path, content: str) -> Path:
    path.write_text(content, encoding="utf-8")
    return path


def read_toml(path: Path) -> dict:
    with open(path, "rb") as fp:
        return tomllib.load(fp)


def package_map(doc: dict) -> dict:
    return {p["name"]: p for p in doc.get("package", [])}


@pytest.fixture
def three_locks(tmp_path):
    base = write(tmp_path / "base.lock", BASE_LOCK)
    ours = write(tmp_path / "ours.lock", OURS_LOCK)
    theirs = write(tmp_path / "theirs.lock", THEIRS_LOCK)
    return base, ours, theirs


def test_merge_lock_command_is_available(tmp_path):
    result = run_merge(tmp_path, "merge-lock", "--help")
    assert result.returncode == 0, result.stderr
    assert "--on-conflict" in result.stdout


def test_clean_three_way_merge(tmp_path, three_locks):
    base, ours, theirs = three_locks
    out = tmp_path / "merged.lock"
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out))
    assert result.returncode == 0, result.stderr
    assert out.exists()
    doc = read_toml(out)
    packages = package_map(doc)
    # versions bumped on either side are combined
    assert packages["alpha"]["version"] == "1.1.0"
    assert packages["beta"]["version"] == "1.2.0"
    # additions from both sides are kept
    assert packages["gamma"]["version"] == "2.0.0"
    assert packages["gamma"]["groups"] == ["dev"]
    assert packages["delta"]["version"] == "0.3"
    # removed on one side, untouched on the other -> removed
    assert "legacy" not in packages
    # file hashes follow the version that was kept
    alpha_files = {row["file"]: row["hash"] for row in packages["alpha"]["files"]}
    assert alpha_files == {
        "alpha-1.1.0-py3-none-any.whl": "sha256:a101",
        "alpha-1.1.0.tar.gz": "sha256:a102",
    }
    beta_files = {row["file"]: row["hash"] for row in packages["beta"]["files"]}
    assert beta_files == {
        "beta-1.2.0.tar.gz": "sha256:b201",
        "beta-1.2.0-py3-none-any.whl": "sha256:b202",
    }
    # dependencies of merged packages are preserved
    assert packages["alpha"]["dependencies"] == ["beta>=1.0"]
    # metadata is merged as well
    metadata = doc["metadata"]
    assert metadata["groups"] == ["default", "dev"]
    assert metadata["strategy"] == ["inherit_metadata"]
    assert metadata["lock_version"] == LOCK_VERSION
    # the content hash follows the working copy (ours)
    assert metadata["content_hash"].endswith("2" * 64)
    assert metadata["targets"] == [{"requires_python": ">=3.9"}]


def test_merge_output_is_a_wellformed_lockfile(tmp_path, three_locks):
    base, ours, theirs = three_locks
    out = tmp_path / "merged.lock"
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out))
    assert result.returncode == 0, result.stderr
    text = out.read_text(encoding="utf-8")
    assert text.startswith("# This file is @generated by PDM.")
    doc = read_toml(out)
    names = [p["name"] for p in doc["package"]]
    assert names == sorted(names), f"packages are not sorted: {names}"


def test_merge_is_deterministic(tmp_path, three_locks):
    base, ours, theirs = three_locks
    out1 = tmp_path / "m1.lock"
    out2 = tmp_path / "m2.lock"
    r1 = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out1))
    r2 = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out2))
    assert r1.returncode == 0 and r2.returncode == 0
    assert out1.read_bytes() == out2.read_bytes()


def test_default_output_overwrites_ours(tmp_path, three_locks):
    base, ours, theirs = three_locks
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(theirs))
    assert result.returncode == 0, result.stderr
    packages = package_map(read_toml(ours))
    assert packages["alpha"]["version"] == "1.1.0"
    assert packages["beta"]["version"] == "1.2.0"
    assert set(packages) == {"alpha", "beta", "gamma", "delta"}


def test_version_conflict_fails_without_strategy(tmp_path):
    base = write(tmp_path / "base.lock", BASE_LOCK)
    ours = write(tmp_path / "ours.lock", CONFLICT_OURS)
    theirs = write(tmp_path / "theirs.lock", CONFLICT_THEIRS)
    out = tmp_path / "merged.lock"
    before = ours.read_bytes()
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out))
    assert result.returncode != 0
    combined = result.stdout + result.stderr
    assert "alpha" in combined
    assert "1.1.0" in combined and "1.5.0" in combined
    # nothing is written when conflicts remain
    assert not out.exists()
    assert ours.read_bytes() == before


@pytest.mark.parametrize(
    "strategy,expected",
    [("newer", "1.5.0"), ("ours", "1.1.0"), ("theirs", "1.5.0")],
)
def test_version_conflict_strategies(tmp_path, strategy, expected):
    base = write(tmp_path / "base.lock", BASE_LOCK)
    ours = write(tmp_path / "ours.lock", CONFLICT_OURS)
    theirs = write(tmp_path / "theirs.lock", CONFLICT_THEIRS)
    out = tmp_path / "merged.lock"
    result = run_merge(
        tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out),
        f"--on-conflict={strategy}",
    )
    assert result.returncode == 0, result.stderr
    packages = package_map(read_toml(out))
    assert packages["alpha"]["version"] == expected
    if strategy == "newer":
        alpha_files = {row["file"] for row in packages["alpha"]["files"]}
        assert "alpha-1.5.0.tar.gz" in alpha_files


def test_removal_vs_modification_is_a_conflict(tmp_path):
    base = write(tmp_path / "base.lock", BASE_LOCK)
    ours = write(tmp_path / "ours.lock", OURS_LOCK)  # bumps alpha
    theirs = write(tmp_path / "theirs.lock", REMOVE_THEIRS)  # removes alpha
    out = tmp_path / "merged.lock"
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out))
    assert result.returncode != 0
    assert "alpha" in result.stdout + result.stderr
    assert not out.exists()
    # newer keeps the modification
    result = run_merge(
        tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out),
        "--on-conflict=newer",
    )
    assert result.returncode == 0, result.stderr
    packages = package_map(read_toml(out))
    assert packages["alpha"]["version"] == "1.1.0"
    # theirs applies the removal
    out2 = tmp_path / "merged2.lock"
    result = run_merge(
        tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out2),
        "--on-conflict=theirs",
    )
    assert result.returncode == 0, result.stderr
    assert "alpha" not in package_map(read_toml(out2))


def test_dry_run_writes_nothing(tmp_path, three_locks):
    base, ours, theirs = three_locks
    before = ours.read_bytes()
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(theirs), "--dry-run")
    assert result.returncode == 0, result.stderr
    assert ours.read_bytes() == before
    # conflicting input makes the dry run fail
    conflict_theirs = write(tmp_path / "theirs2.lock", CONFLICT_THEIRS)
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(conflict_theirs), "--dry-run")
    assert result.returncode != 0
    assert ours.read_bytes() == before


def test_json_report(tmp_path, three_locks):
    base, ours, theirs = three_locks
    out = tmp_path / "merged.lock"
    result = run_merge(
        tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out), "--json"
    )
    assert result.returncode == 0, result.stderr
    report = json.loads(result.stdout)
    assert report["clean"] is True
    assert report["conflicts"] == []
    assert report["packages"] == 4
    changes = report["changes"]
    assert any(name.startswith("gamma") for name in changes["added"])
    assert any(name.startswith("delta") for name in changes["added"])
    assert any(name.startswith("legacy") for name in changes["removed"])
    assert any(name.startswith("alpha") for name in changes["updated"])
    assert any(name.startswith("beta") for name in changes["updated"])
    # conflicting run reports the details as JSON on stdout
    conflict_theirs = write(tmp_path / "theirs2.lock", CONFLICT_THEIRS)
    out2 = tmp_path / "merged2.lock"
    result = run_merge(
        tmp_path, "merge-lock", str(base), str(ours), str(conflict_theirs), "-o", str(out2), "--json"
    )
    assert result.returncode != 0
    report = json.loads(result.stdout)
    assert report["clean"] is False
    conflict_packages = {c["package"] for c in report["conflicts"]}
    assert "alpha" in conflict_packages
    assert not out2.exists()


def test_diverging_lock_strategies_are_rejected(tmp_path):
    base = write(tmp_path / "base.lock", BASE_LOCK)
    ours = write(tmp_path / "ours.lock", STATIC_OURS)  # switched to static_urls
    theirs = write(tmp_path / "theirs.lock", THEIRS_LOCK.replace(
        'strategy = ["inherit_metadata"]', 'strategy = ["cross_platform", "inherit_metadata"]'
    ))
    out = tmp_path / "merged.lock"
    result = run_merge(tmp_path, "merge-lock", str(base), str(ours), str(theirs), "-o", str(out))
    assert result.returncode != 0
    assert "strategy" in (result.stdout + result.stderr).lower()
    assert not out.exists()


def test_strategy_change_on_one_side_is_merged(tmp_path):
    base = write(tmp_path / "base.lock", BASE_LOCK)
    ours = write(tmp_path / "ours.lock", STATIC_OURS)
    theirs = write(tmp_path / "theirs.lock", THEIRS_LOCK)
