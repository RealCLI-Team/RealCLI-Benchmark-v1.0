def test_dataset_to_excel_contract(tmp_path):
    dataset = Dataset.from_dict(
        {
            "name": ["alice", "bob", "carol"],
            "age": [30, 25, 41],
            "score": [9.5, 7.25, 8.0],
            "active": [True, False, True],
        }
    )
    output = tmp_path / "out.xlsx"
    written = dataset.to_excel(str(output))
    # the return value is the number of data rows written (header excluded)
    # and it is a plain int, NOT a byte count or a bool
    assert isinstance(written, int)
    assert not isinstance(written, bool)
    assert written == 3
    workbook = openpyxl.load_workbook(output)
    # default worksheet name
    assert workbook.sheetnames == ["Sheet1"]
    worksheet = workbook["Sheet1"]
    rows = [list(row) for row in worksheet.iter_rows(values_only=True)]
    assert rows == [
        ["name", "age", "score", "active"],
        ["alice", 30, 9.5, True],
        ["bob", 25, 7.25, False],
        ["carol", 41, 8.0, True],
    ]
    # types are preserved as real cells, not strings
    assert isinstance(worksheet["B2"].value, int)
    assert isinstance(worksheet["C2"].value, float)
    assert isinstance(worksheet["D2"].value, bool)


