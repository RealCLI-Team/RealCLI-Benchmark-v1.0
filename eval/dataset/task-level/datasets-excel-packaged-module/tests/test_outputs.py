def test_regression_csv_still_loads(tmp_path):
    csv_path = tmp_path / "regression.csv"
    csv_path.write_text("col_1,col_2\n1,alpha\n2,beta\n3,gamma\n", encoding="utf-8")
    dataset = datasets.load_dataset("csv", data_files=str(csv_path), split="train", cache_dir=tmp_path / "cache")
    assert dataset.column_names == ["col_1", "col_2"]
    assert dataset[:] == {"col_1": [1, 2, 3], "col_2": ["alpha", "beta", "gamma"]}


def test_regression_json_still_loads(tmp_path):
    json_path = tmp_path / "regression.jsonl"
    with open(json_path, "w", encoding="utf-8") as handle:
        for row in [{"col_1": 1, "col_2": "alpha"}, {"col_1": 2, "col_2": "beta"}]:
            handle.write(_stdlib_json.dumps(row))
            handle.write("\n")
    dataset = datasets.load_dataset("json", data_files=str(json_path), split="train", cache_dir=tmp_path / "cache")
    assert dataset[:] == {"col_1": [1, 2], "col_2": ["alpha", "beta"]}


def test_regression_parquet_still_loads(tmp_path):
    pa = pytest.importorskip("pyarrow")
    import pyarrow.parquet as pq

    table = pa.table({"col_1": [1, 2, 3], "col_2": ["alpha", "beta", "gamma"]})
    parquet_path = tmp_path / "regression.parquet"
    pq.write_table(table, parquet_path)
    dataset = datasets.load_dataset("parquet", data_files=str(parquet_path), split="train", cache_dir=tmp_path / "cache")
    assert dataset[:] == {"col_1": [1, 2, 3], "col_2": ["alpha", "beta", "gamma"]}


def test_regression_from_csv_class_method_still_works(tmp_path):
    csv_path = tmp_path / "regression_from_csv.csv"
    csv_path.write_text("a,b\n1,x\n2,y\n", encoding="utf-8")
    dataset = Dataset.from_csv(str(csv_path), cache_dir=tmp_path / "cache")
    assert dataset[:] == {"a": [1, 2], "b": ["x", "y"]}


def test_regression_streaming_csv_still_works(tmp_path):
    csv_path = tmp_path / "streamed.csv"
    csv_path.write_text("a,b\n1,x\n2,y\n3,z\n", encoding="utf-8")
    dataset = datasets.load_dataset(
        "csv", data_files=str(csv_path), split="train", cache_dir=tmp_path / "cache", streaming=True
    )
    assert isinstance(dataset, IterableDataset)
    assert [row["a"] for row in dataset] == [1, 2, 3]
