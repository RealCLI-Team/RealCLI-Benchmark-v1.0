def test_datasetdict_to_excel(tmp_path):
    dataset_dict = DatasetDict(
        {split: Dataset.from_dict(dict(zip(header, map(list, zip(*rows))))) for split, (header, rows) in DICT_SPLITS.items()}
    )
    output = tmp_path / "dict_out.xlsx"
    written = dataset_dict.to_excel(str(output))
    # one worksheet per split, named after the split, row counts per split
    assert isinstance(written, dict)
    assert written == {"train": 3, "validation": 2, "test": 1}
    workbook = openpyxl.load_workbook(output)
    assert workbook.sheetnames == ["train", "validation", "test"]
    train_rows = [list(row) for row in workbook["train"].iter_rows(values_only=True)]
    assert train_rows == [["col_1", "col_2"], [1, "a"], [2, "b"], [3, "c"]]
    test_rows = [list(row) for row in workbook["test"].iter_rows(values_only=True)]
    assert test_rows == [["col_1", "col_2"], [100, "z"]]
    # a written workbook can be read back sheet by sheet
    reloaded = Dataset.from_excel(str(output), sheet_name="validation", cache_dir=tmp_path / "cache")
    assert reloaded[:] == {"col_1": [10, 20], "col_2": ["x", "y"]}


