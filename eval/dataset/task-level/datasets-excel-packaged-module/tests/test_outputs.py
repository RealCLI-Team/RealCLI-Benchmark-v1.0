def test_base_known_extensions_includes_workbook_formats():
    """xlsx/xlsm workbooks are zip containers under the hood. Their extensions must be
    registered as known-native so that `_get_extraction_protocol` short-circuits on the
    extension check and does not try to unzip them by magic-number sniffing."""
    from datasets.utils.file_utils import BASE_KNOWN_EXTENSIONS

    assert "xlsx" in BASE_KNOWN_EXTENSIONS
    assert "xlsm" in BASE_KNOWN_EXTENSIONS
    assert "xls" in BASE_KNOWN_EXTENSIONS


def test_get_extraction_protocol_returns_none_for_workbook_paths(tmp_path):
    """A real xlsx file with the PK\\x03\\x04 magic bytes must NOT be detected as zip.
    Without adding the workbook extensions to BASE_KNOWN_EXTENSIONS, the magic-number
    branch would run and return "zip"."""
    from datasets.utils.file_utils import _get_extraction_protocol

    xlsx_path = _make_workbook(tmp_path / "wb.xlsx", [["a", "b"], [1, 2]])
    assert _get_extraction_protocol(xlsx_path) is None

    xlsm_path = str(tmp_path / "wb.xlsm")
    # copy the xlsx bytes under the xlsm extension — same zip container underneath
    with open(xlsx_path, "rb") as source, open(xlsm_path, "wb") as destination:
        destination.write(source.read())
    assert _get_extraction_protocol(xlsm_path) is None


